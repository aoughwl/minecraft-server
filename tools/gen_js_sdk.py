"""Generates src/plugin/engine/jssdk.aowl (the JavaScript SDK as a string constant the server puts in front of every JavaScript plugin)
from plugin_sdk/pluginsdk.js. Run it after editing that file:  python tools/gen_js_sdk.py"""
import os
here = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(here, '..', 'plugin_sdk', 'pluginsdk.js')
out = os.path.join(here, '..', 'src', 'plugin', 'engine', 'jssdk.aowl')
text = open(src, encoding='utf-8').read().replace('\r\n', '\n')
assert '"""' not in text, 'the SDK must not contain three double quotes in a row'
with open(out, 'w', encoding='utf-8', newline='\n') as f:
    f.write('## Generated by tools/gen_js_sdk.py from plugin_sdk/pluginsdk.js. Do not edit: edit that file and run the script.\n\n')
    f.write('const JsSdkSource* = """\n')
    f.write(text)
    if not text.endswith('\n'):
        f.write('\n')
    f.write('"""\n')
print('wrote', os.path.normpath(out), len(text), 'characters')
