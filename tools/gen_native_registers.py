#!/usr/bin/env python3
"""Writes the uniquely named registration procs of plugin_sdk/pluginsdk.aowl.

The SDK registers a handler with `registerEvent(handler)`, one overload per event type (the handler's parameter type picks the event).
The engine's ahead-of-time toolchain (tools/aoe_native.js, used for native plugin images) cannot choose between overloads that differ only
inside a proc-typed parameter, so for a native build tools/build_plugin.sh rewrites each `registerEvent(handler)` call to
`register_<EventType>(handler)`, reading the type from the handler's `proc handler(e: var <EventType>)`. This script generates those
procs (copies of the overloads' bodies) between two marker lines at the end of the SDK; run it after adding an event type.

    python tools/gen_native_registers.py
"""
import re
import sys
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SDK = os.path.join(HERE, '..', 'plugin_sdk', 'pluginsdk.aowl')
BEGIN = '# ---- generated by tools/gen_native_registers.py: begin (do not edit)'
END = '# ---- generated by tools/gen_native_registers.py: end'

text = open(SDK, encoding='utf-8', newline='').read()
crlf = '\r\n' in text
text = text.replace('\r\n', '\n')
if BEGIN in text:
    text = text[:text.index(BEGIN)].rstrip('\n') + '\n'

lines = text.split('\n')
out = []
i = 0
count = 0
while i < len(lines):
    m = re.match(r'^proc registerEvent\*\(h: proc \(e: var (\w+)\) \{\.nimcall\.\}\) =\s*$', lines[i])
    if m:
        kind = m.group(1)
        body = []
        i += 1
        while i < len(lines) and (lines[i].startswith('  ') or lines[i].strip() == ''):
            if lines[i].strip() == '':
                break
            body.append(lines[i])
            i += 1
        out.append('proc register_%s*(h: proc (e: var %s) {.nimcall.}) =' % (kind, kind))
        out.extend(body)
        count += 1
        continue
    i += 1

new = text.rstrip('\n') + '\n\n' + BEGIN + '\n' + '\n'.join(out) + '\n' + END + '\n'
open(SDK, 'w', encoding='utf-8', newline='').write(new.replace('\n', '\r\n') if crlf else new)
print('wrote %d register_<Event> procs' % count)
